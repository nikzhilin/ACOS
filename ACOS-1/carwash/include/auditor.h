/**
 * @file auditor.h
 * @brief Аудитор инвариантов: проверяет линию после каждого события.
 *
 * Инварианты варианта 43:
 *  - I1 на посту не больше одной машины;
 *  - I2 машина ровно в одном месте (очередь или пост);
 *  - I3 стадии идут в порядке программы;
 *  - I4 сломанный пост не начинает операцию;
 *  - I5 очередь не переполнена.
 *
 * Порядок стадий и поломки аудитор отслеживает сам по событиям, а не берёт у line.c.
 */
#ifndef AUDITOR_H
#define AUDITOR_H

#include "events.h"

/// Куда печатать нарушения (обычно 2, stderr).
void AuditorInit(int errFd);

/// Подписчик шины: обновляет свой учёт и проверяет все инварианты.
void AuditorListener(const Event *e, const struct Line *line);

/// Итоговый отчёт: сколько проверок и какие инварианты нарушались.
void AuditorPrint(int fd);
void AuditorFree(void);

long AuditorChecks(void);      ///< сколько событий проверено
long AuditorViolations(void);  ///< сколько нарушений найдено (больше 0 - код выхода 4)

#endif
